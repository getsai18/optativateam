-- Archivo: postgres.sql   (traducción de RDS(Oracle)/oracle.sql)
-- Fuente de verdad: frontend/src (shared/types/domain.ts y servicios)
--
-- Reparto de datos del proyecto:
--   RDS MySQL     -> clientes, usuarios, emisor, facturas, detalle, pagos, folios
--   RDS Postgres  -> catálogo: servicios, características, impuestos e historial (este archivo)
--   DynamoDB      -> auditoría, eventos de factura, sesiones, carrito del wizard
--
-- Este módulo es autocontenido: ninguna tabla referencia a MySQL. Las facturas (en MySQL)
-- apuntan a service.id y tax.id sin FK y guardan snapshots (tax_code, tax_name, tasa, importe).
-- Quién cambió una tasa queda en tax_history.changed_by y en la auditoría de DynamoDB.
--
-- Es NO destructivo: usa CREATE ... IF NOT EXISTS. Para recrear desde cero descomenta el
-- bloque "REINICIO" (borra todos los datos del catálogo).
-- Ejecutar con:  psql -h <endpoint> -U <usuario> -d <base> -f postgres.sql
-- =============================================================================

