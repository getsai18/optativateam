-- -----------------------------------------------------------------------------
-- 1. Impuestos e historial de tasas
--    Frontend: Tax { code, name, currentRate } y TaxRateHistory
--    (vigencia validFrom <= fecha < validTo; validTo exclusivo, NULL = abierto)
-- -----------------------------------------------------------------------------
CREATE TABLE tax (
    id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code         VARCHAR2(20)   NOT NULL,
    name         VARCHAR2(80)   NOT NULL,
    current_rate NUMBER(6,4)    NOT NULL,
    active       NUMBER(1)      DEFAULT 1 NOT NULL,
    CONSTRAINT pk_tax       PRIMARY KEY (id),
    CONSTRAINT uq_tax_code  UNIQUE (code),
    CONSTRAINT ck_tax_rate  CHECK (current_rate >= 0 AND current_rate <= 1),
    CONSTRAINT ck_tax_active CHECK (active IN (0, 1))
);

CREATE TABLE tax_history (
    id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tax_id     NUMBER       NOT NULL,
    rate       NUMBER(6,4)  NOT NULL,
    valid_from DATE         NOT NULL,
    valid_to   DATE         NULL,              -- exclusivo; NULL = tasa vigente
    created_at TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_tax_history       PRIMARY KEY (id),
    -- En Oracle un UNIQUE compuesto trata (tax_id, NULL) como duplicado, así que
    -- esto garantiza A LO SUMO UN periodo abierto por impuesto y no repite fecha fin.
    CONSTRAINT uq_tax_history_end   UNIQUE (tax_id, valid_to),
    CONSTRAINT fk_tax_history_tax   FOREIGN KEY (tax_id) REFERENCES tax (id),
    CONSTRAINT ck_tax_history_rate  CHECK (rate >= 0 AND rate <= 1),
    CONSTRAINT ck_tax_history_dates CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX ix_tax_history_tax_dates ON tax_history (tax_id, valid_from, valid_to);

-- -----------------------------------------------------------------------------
-- 2. Catálogo de servicios y características
--    Frontend: Service { code, name, description, basePrice, category, taxIds[], features[], active }
--    Frontend: Feature { name, description, unit? } + ServiceFeatureValue { featureId, value }
-- -----------------------------------------------------------------------------
CREATE TABLE service (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code        VARCHAR2(20)   NOT NULL,          -- SKU legible (ej. CLD-0001)
    name        VARCHAR2(120)  NOT NULL,
    description VARCHAR2(2000) NULL,
    base_price  NUMBER(10,2)   NOT NULL,
    category    VARCHAR2(40)   NOT NULL,          -- enum fijo del frontend
    active      NUMBER(1)      DEFAULT 1 NOT NULL,
    created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_service       PRIMARY KEY (id),
    CONSTRAINT uq_service_code  UNIQUE (code),
    CONSTRAINT ck_service_price CHECK (base_price >= 0),
    CONSTRAINT ck_service_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_service_category CHECK (category IN (
        'Cloud Infrastructure', 'Software Licenses', 'Support & Maintenance',
        'Consulting', 'Training', 'Security', 'Data & Analytics', 'Development'))
);

CREATE INDEX ix_service_active_name ON service (active, name);

CREATE TABLE feature (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    name        VARCHAR2(100)  NOT NULL,
    description VARCHAR2(1000) NULL,
    unit        VARCHAR2(30)   NULL,              -- ej. dias, GB, horas
    CONSTRAINT pk_feature      PRIMARY KEY (id),
    CONSTRAINT uq_feature_name UNIQUE (name)
);

-- Asociación N:M con valor (frontend: Service.features: ServiceFeatureValue[])
-- Sin ON DELETE en feature_id: no se borra una característica asignada.
CREATE TABLE service_feature (
    id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    service_id NUMBER        NOT NULL,
    feature_id NUMBER        NOT NULL,
    value      VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_service_feature      PRIMARY KEY (id),
    CONSTRAINT uq_service_feature      UNIQUE (service_id, feature_id),
    CONSTRAINT fk_sf_service FOREIGN KEY (service_id) REFERENCES service (id) ON DELETE CASCADE,
    CONSTRAINT fk_sf_feature FOREIGN KEY (feature_id) REFERENCES feature (id)
);

CREATE INDEX ix_service_feature_feature ON service_feature (feature_id);

-- Impuestos asignados a un servicio (frontend: Service.taxIds[])
CREATE TABLE service_tax (
    service_id NUMBER NOT NULL,
    tax_id     NUMBER NOT NULL,
    CONSTRAINT pk_service_tax      PRIMARY KEY (service_id, tax_id),
    CONSTRAINT fk_service_tax_srv  FOREIGN KEY (service_id) REFERENCES service (id) ON DELETE CASCADE,
    CONSTRAINT fk_service_tax_tax  FOREIGN KEY (tax_id)     REFERENCES tax (id)
);

CREATE INDEX ix_service_tax_tax ON service_tax (tax_id);

-- -----------------------------------------------------------------------------
-- 3. updated_at automático de service (equivale a ON UPDATE CURRENT_TIMESTAMP)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_service_bu
BEFORE UPDATE ON service
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
