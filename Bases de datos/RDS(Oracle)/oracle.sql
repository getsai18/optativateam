-- -----------------------------------------------------------------------------
-- 1. Clientes (receptores de factura)
--    Frontend: Customer { name, taxId, email, phone?, address, active }
-- -----------------------------------------------------------------------------
CREATE TABLE customer (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    name        VARCHAR2(150)  NOT NULL,
    tax_id      VARCHAR2(20)   NOT NULL,          -- Customer.taxId (RFC u homólogo)
    email       VARCHAR2(100)  NOT NULL,
    phone       VARCHAR2(30)   NULL,
    address     VARCHAR2(255)  NOT NULL,
    active      NUMBER(1)      DEFAULT 1 NOT NULL,
    created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_customer      PRIMARY KEY (id),
    CONSTRAINT uq_customer_tax  UNIQUE (tax_id),   -- el frontend solo valida unicidad de taxId
    CONSTRAINT ck_customer_active CHECK (active IN (0, 1))
);

COMMENT ON TABLE customer IS 'Clientes receptores de factura (frontend: CustomersPage)';
COMMENT ON COLUMN customer.tax_id IS 'Identificador fiscal unico (frontend: Customer.taxId)';

-- -----------------------------------------------------------------------------
-- 2. Usuarios de la aplicación
--    Frontend: User { email, fullName, role, customerId?, active } + login
--    Suposición: password_hash lo genera el backend (bcrypt/argon2); el frontend
--    solo envía el password en claro por el formulario de login.
-- -----------------------------------------------------------------------------
CREATE TABLE app_user (
    id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    email          VARCHAR2(100) NOT NULL,
    password_hash  VARCHAR2(255) NOT NULL,
    full_name      VARCHAR2(150) NOT NULL,        -- User.fullName
    role           VARCHAR2(10)  NOT NULL,        -- User.role
    customer_id    NUMBER        NULL,            -- solo rol CUSTOMER
    active         NUMBER(1)     DEFAULT 1 NOT NULL,
    created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user        PRIMARY KEY (id),
    CONSTRAINT uq_app_user_email  UNIQUE (email),
    CONSTRAINT ck_app_user_role   CHECK (role IN ('ADMIN', 'BILLER', 'CUSTOMER')),
    CONSTRAINT ck_app_user_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_app_user_customer_ck CHECK ((role = 'CUSTOMER' AND customer_id IS NOT NULL)
                                          OR (role <> 'CUSTOMER' AND customer_id IS NULL)),
    CONSTRAINT fk_app_user_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE INDEX ix_app_user_customer ON app_user (customer_id);

COMMENT ON TABLE app_user IS 'Usuarios del sistema; rol CUSTOMER enlazado a customer';

-- -----------------------------------------------------------------------------
-- 3. Emisor de facturas (constante del frontend: shared/constants/company.ts)
--    Se snapshotea en cada factura (issuer de Invoice).
-- -----------------------------------------------------------------------------
CREATE TABLE issuer (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    legal_name  VARCHAR2(150) NOT NULL,
    tax_id      VARCHAR2(20)  NOT NULL,
    address     VARCHAR2(255) NOT NULL,
    active      NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_issuer      PRIMARY KEY (id),
    CONSTRAINT uq_issuer_tax  UNIQUE (tax_id),
    CONSTRAINT ck_issuer_active CHECK (active IN (0, 1))
);

COMMENT ON TABLE issuer IS 'Emisor fijo de las facturas (ISSUER del frontend)';

-- -----------------------------------------------------------------------------
-- 4. Impuestos
--    Frontend: Tax { code, name, currentRate } (fracción: 0.16 = 16 %)
-- -----------------------------------------------------------------------------
CREATE TABLE tax (
    id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code         VARCHAR2(20)   NOT NULL,
    name         VARCHAR2(80)   NOT NULL,
    current_rate NUMBER(6,4)    NOT NULL,
    active       NUMBER(1)      DEFAULT 1 NOT NULL,
    CONSTRAINT pk_tax       PRIMARY KEY (id),
    CONSTRAINT uq_tax_code  UNIQUE (code),
    CONSTRAINT ck_tax_rate  CHECK (current_rate >= 0 AND current_rate <= 1),
    CONSTRAINT ck_tax_active CHECK (active IN (0, 1))
);

-- Historial de tasas: vigencia "validFrom <= fecha < validTo" (validTo exclusivo,
-- NULL = vigente). Frontend: TaxRateHistory + rateOnDate() en calculateTotals.ts
CREATE TABLE tax_history (
    id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    tax_id     NUMBER       NOT NULL,
    rate       NUMBER(6,4)  NOT NULL,
    valid_from DATE         NOT NULL,
    valid_to   DATE         NULL,
    changed_by NUMBER       NULL,
    created_at TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_tax_history       PRIMARY KEY (id),
    -- Evita dos periodos con la misma fecha fin. En Oracle, un UNIQUE compuesto
    -- trata (tax_id, NULL) como duplicado, asi que tambien garantiza A LO SUMO
    -- UN periodo abierto (valid_to NULL) por impuesto.
    CONSTRAINT uq_tax_history_end   UNIQUE (tax_id, valid_to),
    CONSTRAINT fk_tax_history_tax   FOREIGN KEY (tax_id)    REFERENCES tax (id),
    CONSTRAINT fk_tax_history_user  FOREIGN KEY (changed_by) REFERENCES app_user (id),
    CONSTRAINT ck_tax_history_rate  CHECK (rate >= 0 AND rate <= 1),
    CONSTRAINT ck_tax_history_dates CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX ix_tax_history_tax_dates ON tax_history (tax_id, valid_from, valid_to);

COMMENT ON COLUMN tax_history.valid_to IS 'Exclusivo; NULL = tasa vigente';

-- -----------------------------------------------------------------------------
-- 5. Catálogo de servicios y características
--    Frontend: Service { code, name, description, basePrice, category, taxIds[], features[], active }
--    Frontend: Feature { name, description, unit? } + ServiceFeatureValue { featureId, value }
-- -----------------------------------------------------------------------------
CREATE TABLE service (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    code        VARCHAR2(20)   NOT NULL,          -- SKU legible (ej. CLD-0001)
    name        VARCHAR2(120)  NOT NULL,
    description VARCHAR2(2000) NULL,
    base_price  NUMBER(10,2)   NOT NULL,
    category    VARCHAR2(40)   NOT NULL,          -- enum fijo del frontend
    active      NUMBER(1)      DEFAULT 1 NOT NULL,
    created_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_service       PRIMARY KEY (id),
    CONSTRAINT uq_service_code  UNIQUE (code),
    CONSTRAINT ck_service_price CHECK (base_price >= 0),
    CONSTRAINT ck_service_active CHECK (active IN (0, 1)),
    CONSTRAINT ck_service_category CHECK (category IN (
        'Cloud Infrastructure', 'Software Licenses', 'Support & Maintenance',
        'Consulting', 'Training', 'Security', 'Data & Analytics', 'Development'))
);

CREATE INDEX ix_service_active_name ON service (active, name);

COMMENT ON COLUMN service.category IS 'Enum fijo del frontend (SERVICE_CATEGORIES en labels.ts)';

CREATE TABLE feature (
    id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    name        VARCHAR2(100)  NOT NULL,
    description VARCHAR2(1000) NULL,
    unit        VARCHAR2(30)   NULL,              -- ej. dias, GB, horas
    CONSTRAINT pk_feature      PRIMARY KEY (id),
    CONSTRAINT uq_feature_name UNIQUE (name)
);

-- Asociación N:M con valor (frontend: Service.features: ServiceFeatureValue[])
CREATE TABLE service_feature (
    id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    service_id NUMBER        NOT NULL,
    feature_id NUMBER        NOT NULL,
    value      VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_service_feature      PRIMARY KEY (id),
    CONSTRAINT uq_service_feature      UNIQUE (service_id, feature_id),
    CONSTRAINT fk_sf_service FOREIGN KEY (service_id) REFERENCES service (id) ON DELETE CASCADE,
    CONSTRAINT fk_sf_feature FOREIGN KEY (feature_id) REFERENCES feature (id)
);

CREATE INDEX ix_service_feature_feature ON service_feature (feature_id);

-- Impuestos asignados a un servicio (frontend: Service.taxIds[])
CREATE TABLE service_tax (
    service_id NUMBER NOT NULL,
    tax_id     NUMBER NOT NULL,
    CONSTRAINT pk_service_tax      PRIMARY KEY (service_id, tax_id),
    CONSTRAINT fk_service_tax_srv  FOREIGN KEY (service_id) REFERENCES service (id) ON DELETE CASCADE,
    CONSTRAINT fk_service_tax_tax  FOREIGN KEY (tax_id)     REFERENCES tax (id)
);

CREATE INDEX ix_service_tax_tax ON service_tax (tax_id);

-- -----------------------------------------------------------------------------
-- 6. Facturas
--    Frontend: Invoice { folio?, uuid?, status, customerId, createdBy, issuer,
--                        receiver, lines, subtotal, taxTotal, total, fechas, ... }
-- -----------------------------------------------------------------------------
CREATE TABLE invoice (
    id                  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    uuid                VARCHAR2(36)   NULL,       -- asignado al emitir (null en borrador)
    folio               VARCHAR2(20)   NULL,       -- ej. INV-2026-0001; solo al emitir
    issuer_id           NUMBER         NOT NULL,
    customer_id         NUMBER         NOT NULL,
    created_by          NUMBER         NOT NULL,
    status              VARCHAR2(10)   DEFAULT 'DRAFT' NOT NULL,
    receiver_name       VARCHAR2(150)  NOT NULL,   -- snapshot del receptor
    receiver_tax_id     VARCHAR2(20)   NOT NULL,
    receiver_address    VARCHAR2(255)  NOT NULL,
    subtotal            NUMBER(12,2)   DEFAULT 0 NOT NULL,
    tax_total           NUMBER(12,2)   DEFAULT 0 NOT NULL,
    total               NUMBER(12,2)   DEFAULT 0 NOT NULL,
    created_at          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    issued_at           TIMESTAMP      NULL,
    paid_at             TIMESTAMP      NULL,
    cancelled_at        TIMESTAMP      NULL,
    cancellation_reason VARCHAR2(255)  NULL,
    CONSTRAINT pk_invoice        PRIMARY KEY (id),
    CONSTRAINT uq_invoice_uuid   UNIQUE (uuid),
    CONSTRAINT uq_invoice_folio  UNIQUE (folio),
    CONSTRAINT ck_invoice_status CHECK (status IN ('DRAFT', 'ISSUED', 'PAID', 'CANCELLED')),
    CONSTRAINT ck_invoice_amounts CHECK (subtotal >= 0 AND tax_total >= 0 AND total >= 0),
    CONSTRAINT fk_invoice_issuer   FOREIGN KEY (issuer_id)   REFERENCES issuer (id),
    CONSTRAINT fk_invoice_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT fk_invoice_user     FOREIGN KEY (created_by)  REFERENCES app_user (id),
    CONSTRAINT ck_invoice_cancel_ck CHECK ((status = 'CANCELLED' AND cancellation_reason IS NOT NULL)
                                        OR status <> 'CANCELLED')
);

CREATE INDEX ix_invoice_customer       ON invoice (customer_id);
CREATE INDEX ix_invoice_created_by     ON invoice (created_by);
CREATE INDEX ix_invoice_status_issued  ON invoice (status, issued_at);
CREATE INDEX ix_invoice_status_created ON invoice (status, created_at);

COMMENT ON COLUMN invoice.uuid IS 'UUID v4 asignado al emitir (stamp() del frontend)';
COMMENT ON COLUMN invoice.receiver_name IS 'Snapshot de Customer.name al emitir';

-- Detalle: snapshot de nombre y precios al momento de agregar la línea
CREATE TABLE invoice_detail (
    id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    invoice_id     NUMBER        NOT NULL,
    service_id     NUMBER        NOT NULL,
    service_name   VARCHAR2(120) NOT NULL,        -- snapshot (InvoiceLine.serviceName)
    quantity       NUMBER(4)     NOT NULL,        -- 1..9999 (valida el frontend)
    unit_price     NUMBER(10,2)  NOT NULL,        -- snapshot de service.base_price
    line_subtotal  NUMBER(12,2)  NOT NULL,
    tax_amount     NUMBER(12,2)  DEFAULT 0 NOT NULL,
    line_total     NUMBER(12,2)  NOT NULL,
    CONSTRAINT pk_invoice_detail        PRIMARY KEY (id),
    CONSTRAINT uq_invoice_detail_line   UNIQUE (invoice_id, service_id),
    CONSTRAINT fk_idetail_invoice FOREIGN KEY (invoice_id) REFERENCES invoice (id) ON DELETE CASCADE,
    CONSTRAINT fk_idetail_service FOREIGN KEY (service_id) REFERENCES service (id),
    CONSTRAINT ck_idetail_qty    CHECK (quantity > 0 AND quantity <= 9999)
);

CREATE INDEX ix_invoice_detail_invoice ON invoice_detail (invoice_id);
CREATE INDEX ix_invoice_detail_service ON invoice_detail (service_id);

-- Desglose por impuesto de cada línea (frontend: InvoiceLine.taxes: InvoiceLineTax[])
-- Es la base del desglose que muestra el comprobante (breakdown.ts)
CREATE TABLE invoice_detail_tax (
    id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    invoice_detail_id NUMBER       NOT NULL,
    tax_id            NUMBER       NOT NULL,
    tax_code          VARCHAR2(20) NOT NULL,      -- snapshot (InvoiceLineTax.code)
    rate              NUMBER(6,4)  NOT NULL,      -- tasa vigente al calcular
    amount            NUMBER(12,2) NOT NULL,
    CONSTRAINT pk_invoice_detail_tax      PRIMARY KEY (id),
    CONSTRAINT uq_invoice_detail_tax      UNIQUE (invoice_detail_id, tax_id),
    CONSTRAINT fk_idtax_detail FOREIGN KEY (invoice_detail_id) REFERENCES invoice_detail (id) ON DELETE CASCADE,
    CONSTRAINT fk_idtax_tax    FOREIGN KEY (tax_id)            REFERENCES tax (id),
    CONSTRAINT ck_idtax_rate   CHECK (rate >= 0 AND rate <= 1),
    CONSTRAINT ck_idtax_amount CHECK (amount >= 0)
);

CREATE INDEX ix_invoice_detail_tax_tax ON invoice_detail_tax (tax_id);

COMMENT ON TABLE invoice_detail_tax IS 'Snapshot de tasa e importe por impuesto y línea (InvoiceLineTax)';

-- Contador de folios por año (frontend: Db.folioCounters: Record<year, number>)
CREATE TABLE folio_counter (
    year        NUMBER(4)    NOT NULL,
    last_number NUMBER(10)   DEFAULT 0 NOT NULL,
    CONSTRAINT pk_folio_counter PRIMARY KEY (year),
    CONSTRAINT ck_folio_year CHECK (year BETWEEN 2000 AND 2100)
);

-- -----------------------------------------------------------------------------
-- 7. Pagos (simulados)
--    Frontend: Payment { invoiceId, method, amount, reference, paidAt, registeredBy }
--    Regla del frontend: un solo pago total por factura emitida.
-- -----------------------------------------------------------------------------
CREATE TABLE payment (
    id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    invoice_id    NUMBER         NOT NULL,
    method        VARCHAR2(10)   NOT NULL,        -- PaymentMethod del frontend
    amount        NUMBER(12,2)   NOT NULL,
    reference     VARCHAR2(60)   NULL,            -- referencia simulada (SIM-XXXXXX)
    paid_at       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    registered_by NUMBER         NOT NULL,
    CONSTRAINT pk_payment        PRIMARY KEY (id),
    CONSTRAINT uq_payment_invoice UNIQUE (invoice_id),  -- un pago por factura (frontend)
    CONSTRAINT fk_payment_invoice FOREIGN KEY (invoice_id)    REFERENCES invoice (id),
    CONSTRAINT fk_payment_user    FOREIGN KEY (registered_by) REFERENCES app_user (id),
    CONSTRAINT ck_payment_method  CHECK (method IN ('CARD', 'TRANSFER', 'CASH')),
    CONSTRAINT ck_payment_amount  CHECK (amount > 0)
);

CREATE INDEX ix_payment_registered_by ON payment (registered_by);

-- -----------------------------------------------------------------------------
-- 8. updated_at automático (3 triggers, igual que ON UPDATE CURRENT_TIMESTAMP)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_customer_bu
BEFORE UPDATE ON customer
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER trg_app_user_bu
BEFORE UPDATE ON app_user
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER trg_service_bu
BEFORE UPDATE ON service
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

