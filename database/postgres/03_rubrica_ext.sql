DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_tax_kind') THEN
        ALTER TABLE tax ADD CONSTRAINT ck_tax_kind CHECK (kind IN ('TRANSFER', 'WITHHELD'));
    END IF;
END $$;

