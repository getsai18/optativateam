INSERT INTO tax_history (tax_id, rate, valid_from, valid_to)
SELECT t.id, t.current_rate, DATE '2020-01-01', NULL
  FROM tax t
 WHERE t.code IN ('RET_ISR', 'RET_IVA')
   AND NOT EXISTS (SELECT 1 FROM tax_history h WHERE h.tax_id = t.id);

-- -----------------------------------------------------------------------------
-- Auditoría de tarifas de servicios
-- changed_by es el app_user.id de MySQL (referencia lógica entre motores).
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS service_price_history (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    service_id  INTEGER       NOT NULL,
    old_price   NUMERIC(10,2) NULL,
    new_price   NUMERIC(10,2) NOT NULL,
    change_pct  NUMERIC(9,4)  NULL,
    reason      VARCHAR(255)  NULL,
    changed_by  INTEGER       NULL,
    changed_at  TIMESTAMP     NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT pk_service_price_history PRIMARY KEY (id),
    CONSTRAINT fk_sph_service FOREIGN KEY (service_id) REFERENCES service (id) ON DELETE CASCADE,
    CONSTRAINT ck_sph_price CHECK (new_price >= 0 AND (old_price IS NULL OR old_price >= 0))
);

CREATE INDEX IF NOT EXISTS ix_sph_service_date ON service_price_history (service_id, changed_at DESC);

-- El trigger lee el usuario y el motivo de variables de sesión que fija
-- sp_update_service_price (o el backend con set_config). Si no existen, quedan NULL.
CREATE OR REPLACE FUNCTION trg_service_price_audit() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' OR NEW.base_price IS DISTINCT FROM OLD.base_price THEN
        INSERT INTO service_price_history (service_id, old_price, new_price, change_pct, reason, changed_by)
        VALUES (
            NEW.id,
            CASE WHEN TG_OP = 'UPDATE' THEN OLD.base_price END,
            NEW.base_price,
            CASE WHEN TG_OP = 'UPDATE' AND OLD.base_price > 0
                 THEN ROUND((NEW.base_price - OLD.base_price) / OLD.base_price * 100, 4) END,
            NULLIF(current_setting('app.price_reason', true), ''),
            NULLIF(current_setting('app.user_id', true), '')::INTEGER
        );
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_service_price_audit ON service;
CREATE TRIGGER trg_service_price_audit
    AFTER INSERT OR UPDATE OF base_price ON service
    FOR EACH ROW EXECUTE FUNCTION trg_service_price_audit();

-- Precio inicial de los servicios que ya existían
INSERT INTO service_price_history (service_id, old_price, new_price, reason)
SELECT s.id, NULL, s.base_price, 'Precio inicial'
  FROM service s
 WHERE NOT EXISTS (SELECT 1 FROM service_price_history h WHERE h.service_id = s.id);
